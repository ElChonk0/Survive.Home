// Food is split into three tiers by day: no-cook (1–3), pantry (4–14), staples (15+).
// `share` is the fraction of that tier's calories this line supplies.
function tierUnits(c, tier, share, kcalPerUnit) {
  return up((c.kcalDay * c.tiers[tier] * share) / kcalPerUnit);
}
// Staple quantities from video 24: per 1,800 kcal-day, scaled from the 90-day family-of-4 plan.
function staple(c, lbPer90) {
  return up((c.kcalDay / 1800) * (c.tiers.st / 90) * lbPer90 * 10) / 10;
}

